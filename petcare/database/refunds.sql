-- Additive refund and return ledger. Paid invoices remain immutable.
CREATE TABLE IF NOT EXISTS invoice_refunds (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_id BIGINT UNSIGNED NOT NULL,
    invoice_id BIGINT UNSIGNED NOT NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    request_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    method ENUM('cash', 'bank_transfer', 'card', 'other') NOT NULL,
    note VARCHAR(300) NOT NULL DEFAULT '',
    currency_code CHAR(3) CHARACTER SET ascii NOT NULL,
    refund_total DECIMAL(20, 4) NOT NULL,
    UNIQUE KEY uq_invoice_refunds_tenant_id (tenant_id, id),
    UNIQUE KEY uq_invoice_refunds_tenant_invoice_id (tenant_id, invoice_id, id),
    UNIQUE KEY uq_invoice_refunds_request (tenant_id, request_key),
    INDEX idx_invoice_refunds_invoice (tenant_id, invoice_id, created_at, id),
    INDEX idx_invoice_refunds_created (tenant_id, created_at, invoice_id),
    CONSTRAINT fk_invoice_refunds_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE RESTRICT,
    CONSTRAINT fk_invoice_refunds_invoice FOREIGN KEY (tenant_id, invoice_id) REFERENCES invoices(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_invoice_refunds_creator FOREIGN KEY (tenant_id, created_by) REFERENCES tenant_users(tenant_id, user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_invoice_refunds_total CHECK (refund_total >= 0),
    CONSTRAINT chk_invoice_refunds_currency CHECK (currency_code REGEXP '^[A-Z]{3}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS invoice_refund_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_id BIGINT UNSIGNED NOT NULL,
    invoice_id BIGINT UNSIGNED NOT NULL,
    refund_id BIGINT UNSIGNED NOT NULL,
    invoice_item_id BIGINT UNSIGNED NOT NULL,
    item_type_snapshot ENUM('product', 'pet') NOT NULL,
    item_code_snapshot VARCHAR(48) NOT NULL,
    item_name_snapshot VARCHAR(160) NOT NULL,
    quantity INT UNSIGNED NOT NULL,
    unit_price DECIMAL(20, 4) NOT NULL,
    refund_amount DECIMAL(20, 4) NOT NULL,
    disposition ENUM('resell', 'quarantine', 'not_returned') NOT NULL,
    UNIQUE KEY uq_invoice_refund_items_tenant_id (tenant_id, id),
    UNIQUE KEY uq_invoice_refund_items_tenant_refund_id (tenant_id, refund_id, id),
    UNIQUE KEY uq_invoice_refund_items_tenant_invoice_refund_id (tenant_id, invoice_id, refund_id, id),
    UNIQUE KEY uq_invoice_refund_items_line_once (tenant_id, refund_id, invoice_item_id),
    INDEX idx_invoice_refund_items_source (tenant_id, invoice_id, invoice_item_id),
    CONSTRAINT fk_invoice_refund_items_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE RESTRICT,
    CONSTRAINT fk_invoice_refund_items_refund FOREIGN KEY (tenant_id, invoice_id, refund_id) REFERENCES invoice_refunds(tenant_id, invoice_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_invoice_refund_items_invoice FOREIGN KEY (tenant_id, invoice_id) REFERENCES invoices(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_invoice_refund_items_invoice_line FOREIGN KEY (tenant_id, invoice_id, invoice_item_id) REFERENCES invoice_items(tenant_id, invoice_id, id) ON DELETE RESTRICT,
    CONSTRAINT chk_invoice_refund_items_quantity CHECK (quantity > 0 AND (item_type_snapshot = 'product' OR quantity = 1)),
    CONSTRAINT chk_invoice_refund_items_amount CHECK (unit_price >= 0 AND refund_amount = unit_price * quantity)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
