def current_locale():
    """Return a validated locale for the current request or signed session."""
    try:
        locale = getattr(g, "locale", None)
    except RuntimeError:
        locale = None
    if locale in SUPPORTED_LOCALES:
        return locale
    try:
        locale = session.get("locale", "vi")
    except RuntimeError:
        locale = "vi"
    return locale if locale in SUPPORTED_LOCALES else "vi"


